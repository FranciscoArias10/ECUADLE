// Normalize text helper (strips accents, lowercases)
export function normalizeWord(str) {
  if (!str) return "";
  return str
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim();
}

export const VALID_SET = new Set([
  ...ECUADOR_WORDS.map(item => normalizeWord(item.word)),
  ...VALID_EXTRA.map(w => normalizeWord(w))
]);

export function getDailyWord() {
  const now = new Date();
  const ecuadorOffset = -5; // UTC-5
  const utc = now.getTime() + (now.getTimezoneOffset() * 60000);
  const ecuadorTime = new Date(utc + (3600000 * ecuadorOffset));
  
  const startDate = new Date(2024, 0, 1);
  const diffDays = Math.floor((ecuadorTime - startDate) / (1000 * 60 * 60 * 24));
  const index = ((diffDays % ECUADOR_WORDS.length) + ECUADOR_WORDS.length) % ECUADOR_WORDS.length;
  
  return {
    wordData: ECUADOR_WORDS[index],
    normalized: normalizeWord(ECUADOR_WORDS[index].word),
    dayNumber: diffDays
  };
}

